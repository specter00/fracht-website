/* ---------- Zoll-FAQ (export-faq.html) ---------- */

function faq(c, h) {
  const t = c.texts.faq;
  const src = id => {
    const s = c.sources[id];
    if (!s) throw new Error("FAQ references unknown source id: " + id);
    const label = h.esc(s.publisher + ": " + s.title);
    return `<li>${s.url ? `<a href="${h.esc(s.url)}" rel="noopener">${label}</a>` : label}, ${h.esc(t.accessedLabel)} ${h.esc(s.accessed)}</li>`;
  };
  const toc = t.groups.map(g => `<p class="faq-toc-group">${h.tx(g.title)}</p>
        <ol>
          ${g.items.map(i => `<li><a href="#${i.id}">${h.tx(i.q)}</a></li>`).join("\n          ")}
        </ol>`).join("\n        ");
  const items = t.groups.map((g, gi) => `
        <section class="faq-group" aria-labelledby="faq-g${gi}">
          <h2 class="faq-group-title" id="faq-g${gi}">${h.tx(g.title)}</h2>
          ${g.intro ? `<p class="faq-group-intro">${h.tx(g.intro)}</p>` : ""}${g.items.map(i => `
          <article class="faq-item" id="${i.id}">
            <h3>${h.tx(i.q)}</h3>
            ${i.a.map(p => Array.isArray(p) ? `<ul>${p.map(li => `<li>${h.tx(li)}</li>`).join("")}</ul>` : `<p>${h.tx(p)}</p>`).join("\n            ")}
            <div class="faq-sources"><span>${h.esc(i.sources.length > 1 ? t.sourcesLabel : t.sourceLabel)}</span><ul>${i.sources.map(src).join("")}</ul></div>
          </article>`).join("\n")}
        </section>`).join("\n");
  const body = pageHead(h, t.h1, t.intro) + `
  <section class="section section-flush">
    <div class="wrap faq-grid">
      <nav class="faq-toc" aria-label="Fragen">
        ${toc}
      </nav>
      <div class="faq-list">${items}
      </div>
    </div>
  </section>`;
  return layout(c, h, { title: t.title, description: t.description, active: "faq", body });
}

